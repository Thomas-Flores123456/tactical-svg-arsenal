import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const root = fileURLToPath(new URL('../', import.meta.url));
const hash = data => createHash('sha256').update(data).digest('hex');
const baselinePath = path.join(root, 'metadata/source-baseline.json');
const catalogPath = path.join(root, 'metadata/catalog.json');
const classificationPath = path.join(root, 'metadata/classification.json');
const verify = process.argv.includes('--verify');
const classification = JSON.parse(await fs.readFile(classificationPath, 'utf8'));

const categoryIds = classification.categories.map(c => c.id);
if (new Set(categoryIds).size !== categoryIds.length) throw new Error('Duplicate category');
for (const [id, entry] of Object.entries(classification.equipment)) {
  const c = classification.categories.find(c => c.id === entry.categoryId);
  if (!c || (entry.subtypeId && !c.subtypes.some(s => s.id === entry.subtypeId))) {
    throw new Error(`Invalid classification: ${id}`);
  }
}

function classify(id, directory) {
  const entry = classification.equipment[id] ?? { categoryId: 'unclassified', subtypeId: '' };
  const category = classification.categories.find(c => c.id === entry.categoryId);
  const subtype = category.subtypes.find(s => s.id === entry.subtypeId);
  return {
    categoryId: entry.categoryId,
    subtypeId: entry.subtypeId,
    categoryLabel: category.label,
    subtypeLabel: subtype?.label ?? '',
    categoryOrder: categoryIds.indexOf(category.id),
    subtypeOrder: subtype ? category.subtypes.indexOf(subtype) : 0,
    sourceOrder: Number(directory.match(/^\d+/)?.[0] ?? Number.MAX_SAFE_INTEGER),
  };
}

function inferFaction(service, groupName, viewIds, sourceStatus) {
  for (const vid of viewIds) {
    if (vid.includes('.allied.')) return 'allied';
    if (vid.includes('.soviet.')) return 'soviet';
    if (vid.includes('.yuri.')) return 'yuri';
    if (vid.includes('.common.')) return 'common';
  }
  if (/Yuri|尤里/.test(groupName) || /武备·尤里|工程·尤里/.test(sourceStatus)) return 'yuri';
  if (/武备·盟军|工程·盟军/.test(sourceStatus)) return 'allied';
  if (/武备·苏联|工程·苏联/.test(sourceStatus)) return 'soviet';
  if (service === 'navy') {
    if (/^(02_076|04_055|07_)/.test(groupName)) return 'common';
    if (/_(Pr\d+|941型|12322型|RA2_)/.test(groupName)) return 'soviet';
    return 'allied';
  }
  return 'unclassified';
}

function inferPlatform(service) {
  return { navy: 'sea', army: 'land', air: 'air' }[service] ?? 'unclassified';
}

function defaultSourceStatus(id, service, groupName) {
  const custom = classification.equipment[id]?.sourceStatus;
  if (custom) return custom;
  if (service === 'army') {
    const num = Number(groupName.match(/^\d+/)?.[0] ?? 0);
    return num <= 7
      ? '抽取自titan-arsenal既有几何；非实物同比例认证。天启旧口径/重量冲突未定稿。'
      : '参考世界书与实车/设定资料重绘侧顶线图；非实物1:1工程认证。';
  }
  if (groupName.startsWith('02_076')) {
    return '侧视为F70初步草图与新华社实拍的水线上参考复原；顶视沿用旧稿，非官方精确线图';
  }
  return '未复核';
}

const equipment = [], assets = [], hashes = {};
const ids = new Set();

const SERVICE_DIRS = [
  ['assets/navy', 'navy'],
  ['assets/army', 'army'],
  ['assets/air', 'air'],
];

for (const [folder, service] of SERVICE_DIRS) {
  const dir = path.join(root, folder);
  let groups;
  try { groups = await fs.readdir(dir, { withFileTypes: true }); }
  catch (e) { if (e.code === 'ENOENT') continue; throw e; }

  for (const group of groups.filter(x => x.isDirectory() && /^\d+_/.test(x.name)).sort((a, b) => a.name.localeCompare(b.name))) {
    const eid = `${service}:${group.name}`;
    const svgFiles = (await fs.readdir(path.join(dir, group.name))).filter(x => x.endsWith('.svg')).sort();
    if (!svgFiles.length) continue;
    // Skip in-progress draft directories being generated by concurrent agents (missing classification or data-asset-id)
    if (!classification.equipment[eid]) continue;
    const loadedFiles = await Promise.all(svgFiles.map(async file => {
      const relative = [folder, group.name, file].join('/');
      const bytes = await fs.readFile(path.join(root, relative));
      const svg = bytes.toString('utf8');
      const id = svg.match(/data-asset-id="([^"]+)"/)?.[1];
      return { file, relative, bytes, svg, id };
    }));
    if (loadedFiles.some(x => !x.id)) continue;

    const views = [];
    for (const { file, relative, bytes, svg, id } of loadedFiles) {
      if (ids.has(id)) throw new Error(`Duplicate asset ID: ${relative}`);
      ids.add(id);
      const vb = svg.match(/viewBox="\s*([-\d.]+)[ ,]+([-\d.]+)[ ,]+([\d.]+)[ ,]+([\d.]+)\s*"/);
      if (!vb || !(+vb[3] > 0 && +vb[4] > 0)) throw new Error(`Invalid viewBox: ${relative}`);
      hashes[relative] = hash(bytes);
      const kind = /data-view-kind="clean-variant"/.test(svg) || id.endsWith('.clean.variant')
        ? 'clean-variant'
        : /data-view-kind="clean-master"/.test(svg)
          ? 'clean-master'
          : /master|总图|双联|联合工程/.test(id + file)
            ? 'master'
            : 'single';
      const label = svg.match(/data-view-label="([^"]+)"/)?.[1]
        ?? (kind === 'clean-master' ? '纯净侧顶总图' : kind === 'master' ? '联合总图' : /顶视/.test(file) ? '顶视' : /侧视/.test(file) ? '侧视' : '细节');
      const configuration = svg.match(/data-configuration="([^"]+)"/)?.[1];
      const asset = {
        id,
        equipmentId: eid,
        file,
        sourcePath: relative,
        url: `assets/${encodeURIComponent(id)}.svg`,
        width: +vb[3],
        height: +vb[4],
        bytes: bytes.length,
        sha256: hashes[relative],
        kind,
        label,
        ...(configuration ? { configuration } : {}),
        backdrop: /id="layer-backdrop"/.test(svg),
      };
      assets.push(asset);
      views.push(id);
      if (!verify) {
        await fs.mkdir(path.join(root, 'public/assets'), { recursive: true });
        await fs.writeFile(path.join(root, 'public/assets', `${id}.svg`), bytes);
      }
    }
    if (views.length) {
      const sourceStatus = defaultSourceStatus(eid, service, group.name);
      equipment.push({
        id: eid,
        ...classify(eid, group.name),
        name: group.name.replace(/^\d+_/, '').replaceAll('_', ' · '),
        service,
        platform: inferPlatform(service),
        faction: inferFaction(service, group.name, views, sourceStatus),
        sourceStatus,
        views,
        coverId: views.find(id => assets.find(a => a.id === id)?.kind === 'clean-master')
          ?? views.find(id => assets.find(a => a.id === id)?.kind === 'master')
          ?? views[0],
      });
    }
  }
}

if (!verify) {
  const pubDir = path.join(root, 'public/assets');
  for (const f of await fs.readdir(pubDir)) {
    if (f.endsWith('.svg') && !ids.has(f.slice(0, -4))) {
      await fs.unlink(path.join(pubDir, f));
    }
  }
}

let baseline;
try { baseline = JSON.parse(await fs.readFile(baselinePath, 'utf8')); }
catch (e) { if (e.code !== 'ENOENT') throw e; }
if (baseline) {
  for (const [file, digest] of Object.entries(baseline)) {
    if (hashes[file] !== digest) throw new Error(`Source changed or missing: ${file}. Review baseline manually.`);
  }
} else {
  if (verify) throw new Error('Baseline missing');
  await fs.writeFile(baselinePath, JSON.stringify(hashes, null, 2) + '\n');
}

if (verify) {
  const catalog = JSON.parse(await fs.readFile(catalogPath, 'utf8'));
  if (JSON.stringify(catalog.equipment) !== JSON.stringify(equipment)) throw new Error('Equipment classification/index differs from metadata');
  if (catalog.assets.length !== assets.length) throw new Error('Index count differs from sources');
  for (const a of assets) {
    const indexed = catalog.assets.find(x => x.id === a.id);
    if (!indexed || ['sha256', 'kind', 'label', 'configuration', 'equipmentId', 'sourcePath'].some(key => indexed[key] !== a[key])) {
      throw new Error(`Index differs: ${a.id}`);
    }
    const copied = await fs.readFile(path.join(root, 'public/assets', `${a.id}.svg`));
    if (hash(copied) !== a.sha256) throw new Error(`Copy differs: ${a.id}`);
  }
} else {
  await fs.mkdir(path.join(root, 'metadata'), { recursive: true });
  const catalogJson = JSON.stringify({ schemaVersion: 1, equipment, assets }, null, 2) + '\n';
  await fs.writeFile(catalogPath, catalogJson);
  await fs.mkdir(path.join(root, 'public/metadata'), { recursive: true });
  await fs.writeFile(path.join(root, 'public/metadata/catalog.json'), catalogJson);
  await fs.copyFile(classificationPath, path.join(root, 'public/metadata/classification.json'));
}
console.log(`${verify ? 'VERIFIED' : 'INDEXED'}: ${equipment.length} equipment groups, ${assets.length} SVG assets; original SHA-256 preserved.`);
